import { expect, test } from '@playwright/test'
import { mockPaidAuth } from './helpers/paid-auth'

for (const theme of ['light', 'dark']) {
  test(`purple workspace keeps a wide media library and preserves its task during resize in ${theme}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await mockPaidAuth(page)
    await page.addInitScript(theme => localStorage.setItem('scrub-theme', theme), theme)
    await page.route(url => url.pathname === '/list', route => route.fulfill({ json: [] }))
    await page.route('**/sessions**', route => route.fulfill({ json: {} }))
    const project = { id: 'default', name: 'Test project', version: 2, createdAt: '', updatedAt: '' }
    await page.route('**/projects', route => route.fulfill({ json: [project] }))
    await page.route('**/projects/default', route => route.fulfill({ json: { ...project, state: null } }))
    await page.goto('/editor')

    const workspace = page.locator('.editor-suite')
    await expect(workspace).toHaveCSS('background-color', theme === 'light' ? 'rgb(243, 242, 238)' : 'rgb(29, 27, 36)')
    await expect(workspace).toHaveCSS('font-family', /IBM Plex Sans/)
    const mediaTool = page.getByRole('navigation', { name: 'Editor tools' }).getByRole('button', { name: 'Media Bin', exact: true })
    await mediaTool.hover()
    await expect(mediaTool).toHaveClass('active')
    await expect(mediaTool).toHaveAttribute('aria-current', 'page')
    const bin = page.locator('#media-bin-panel')
    await bin.getByRole('button', { name: 'Open media search' }).click()
    await bin.getByRole('searchbox', { name: 'Search media' }).fill('Retain this task')
    await bin.getByRole('button', { name: 'Media bin options' }).click()
    await bin.getByRole('button', { name: 'Grid view', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Focus canvas', exact: true })).toHaveCount(0)
    const resizer = page.getByRole('slider', { name: 'Resize tool deck' })
    await expect(resizer).toHaveAttribute('aria-valuenow', '560')
    await resizer.press('ArrowLeft')
    await expect(resizer).toHaveAttribute('aria-valuenow', '536')
    await expect(bin).toBeVisible()
    await expect(page.locator('.tl')).toBeVisible()
    await resizer.press('ArrowRight')
    await expect(resizer).toHaveAttribute('aria-valuenow', '560')
    await expect(bin.getByRole('searchbox', { name: 'Search media' })).toHaveValue('Retain this task')
    await expect(bin.locator('.list')).not.toHaveClass(/list-view/)
    await mediaTool.click()
    await expect(bin).toBeVisible()
    await expect(bin.getByRole('searchbox', { name: 'Search media' })).toHaveValue('Retain this task')
    await bin.getByRole('searchbox', { name: 'Search media' }).fill('')
    await page.screenshot({ path: testInfo.outputPath(`wide-media-${theme}.png`), fullPage: true, animations: 'disabled' })
    await page.getByRole('button', { name: 'Create a scene', exact: true }).click()
    const scenes = page.getByRole('dialog', { name: 'Generate scenes', exact: true })
    await expect(scenes).toBeVisible()
    await scenes.getByRole('button', { name: 'Close Generate scenes', exact: true }).click()
    await page.getByRole('navigation', { name: 'Editor tools' }).getByRole('button', { name: 'Speech', exact: true }).click()
    const speech = page.locator('#text-to-speech-panel')
    await expect(speech.getByRole('button', { name: 'Clone a voice', exact: true })).toBeHidden()
    await speech.locator('summary').filter({ hasText: 'Voice ·' }).click()
    await expect(speech.getByRole('button', { name: 'Clone a voice', exact: true })).toBeVisible()
    await expect(speech.getByLabel('Model', { exact: true })).toBeHidden()
    await speech.locator('summary').filter({ hasText: 'Generation model' }).click()
    await expect(speech.getByLabel('Model', { exact: true })).toBeVisible()
  })
}
