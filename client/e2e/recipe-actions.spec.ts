  await dialog.getByRole('button', { name: 'Close video recipe' }).click()
  await page.getByRole('button', { name: 'Recipe', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Edit Generate image: image-1' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Apply actions', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('1 clips')
  expect(generations).toBe(1)
  await dialog.getByRole('tab', { name: 'Code DSL' }).click()
