  await dialog.getByLabel('Duration (seconds)', { exact: true }).fill('5')
  await dialog.getByLabel('Horizontal position (%)', { exact: true }).fill('-24')
  await dialog.getByLabel('Scale (%)', { exact: true }).fill('50')
  await expect(dialog.getByRole('button', { name: 'Apply actions', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Add action', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Edit Generate image: image-1' })).toBeVisible()
  await dialog.getByRole('button', { name: /^Generate voice/ }).click()
  await dialog.getByLabel('Script', { exact: true }).fill('Welcome to our coastal town.')
  await dialog.getByRole('combobox', { name: 'Built-in voice', exact: true }).click()
  await dialog.getByRole('button', { name: 'Kore', exact: true }).click()
  await dialog.getByRole('button', { name: 'Add action', exact: true }).click()
