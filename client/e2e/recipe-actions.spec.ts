  await dialog.getByRole('button', { name: 'Edit Generate image: image-1' }).click()
  await expect(dialog.getByLabel('Describe the image', { exact: true })).toHaveValue('A sunlit coastal town, seen from above')
  expect(await dialog.locator('.recipe-action-form h4').first().evaluate((element) => getComputedStyle(element).fontFamily)).toContain('IBM Plex Sans Variable')
