  await dialog.getByRole('button', { name: 'Apply actions', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('1 text items, 3s')
  await dialog.getByRole('button', { name: 'Edit Add text: text-1' }).click()
  await dialog.getByLabel('Text', { exact: true }).fill('Titlu actualizat')
  await dialog.getByRole('button', { name: 'Save action', exact: true }).click()
  await dialog.getByRole('button', { name: 'Apply actions', exact: true }).click()
